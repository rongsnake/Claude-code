"""
Credit risk RWAs: the revised standardised approach and the IRB approach.

Both are implemented because Basel 3.1 forces an IRB firm to run both. The
output floor (see `output_floor.py`) caps total RWAs at a percentage of what
the firm would report if it used the standardised approaches everywhere, so
the SA engine is no longer a fallback — it is a permanent parallel calculation
over the same book.

Structure:
  * `standardised_rwa`  — exposure -> SA risk weight -> RWA
  * `irb_rwa`           — exposure -> Basel risk-weight function -> RWA
  * `credit_rwa`        — dispatches per exposure on its permitted approach,
                          and returns both the live and the all-SA totals

Every risk weight below is the rule as written, tagged REGULATORY. Where the
PRA's UK implementation is known to differ from the Basel text, or where we are
not certain of the final UK position, the constant carries a comment saying so
— those are the lines to check against PS1/26 before anyone relies on a number.
"""

