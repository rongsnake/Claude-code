@dataclass
class CreditRWAResult:
    """Credit RWAs on the live approach and on an all-SA basis (output floor)."""

    live_rwa: float = 0.0
    sa_rwa: float = 0.0
    expected_loss: float = 0.0
    ead: float = 0.0
    by_segment: dict[str, float] = field(default_factory=dict)
    by_approach: dict[str, float] = field(default_factory=dict)

    @property
    def average_risk_weight(self) -> float:
        return safe_div(self.live_rwa, self.ead)


def removed_support_factor_relief(
    exposures: list[CreditExposure], cfg: SAConfig | None = None
) -> tuple[float, float]:
    """RWAs that the withdrawn Pillar 1 supporting factors used to remove.

    Basel 3.1 deletes the SME and infrastructure supporting factors. The PRA
    compensates with firm-specific Pillar 2A lending adjustments (PS7/25)
    calibrated so that overall capital requirements for those exposures do not
    rise. Sizing those adjustments needs the RWA relief that has been lost,
    which is what this returns as (SME, infrastructure).
    """
    cfg = cfg or SAConfig()
    sme_relief = 0.0
    infra_relief = 0.0
    for e in exposures:
        rwa = irb_rwa(e, cfg) if e.approach is not IRBApproach.SA_ONLY else standardised_rwa(e, cfg)
        if e.sme or e.exposure_class is ExposureClass.CORPORATE_SME:
            sme_relief += rwa * (1.0 - SME_SUPPORT_FACTOR)
        elif e.infrastructure:
            infra_relief += rwa * (1.0 - INFRASTRUCTURE_SUPPORT_FACTOR)
    return sme_relief, infra_relief


def credit_rwa(
    exposures: list[CreditExposure], cfg: SAConfig | None = None
) -> CreditRWAResult:
    """Run both engines over the whole banking book."""
    cfg = cfg or SAConfig()
    res = CreditRWAResult()

    for e in exposures:
        sa = standardised_rwa(e, cfg)
        if e.approach is IRBApproach.SA_ONLY:
            live = sa
        else:
            live = irb_rwa(e, cfg)
            res.expected_loss += irb_expected_loss(e, cfg)

        res.live_rwa += live
        res.sa_rwa += sa
        res.ead += irb_ead(e, cfg) if e.approach is not IRBApproach.SA_ONLY else sa_exposure_at_default(e)
        res.by_segment[e.segment] = res.by_segment.get(e.segment, 0.0) + live
        res.by_approach[e.approach.value] = res.by_approach.get(e.approach.value, 0.0) + live

    return res
